function _generateBitmapMatrix (needed) {
    let lightsArray = [],
        currX = 0;
    for (let x = 0; x < needed.length; x++) {
        let maxWidth = 0;
        for (let i = 0; i < needed[x].length; i++) {
            if (!lightsArray[i]) {
                lightsArray[i] = [];
            }

            for (let j = 0; j < needed[x][i].length; j++) {
                maxWidth = (needed[x][i].length > maxWidth) ? needed[x][i].length : maxWidth;
                if (needed[x][i][j]) {
                    lightsArray[i][j + currX] = 1;
                }
            }
        }
        currX += maxWidth + 1;
    }

    return lightsArray;
}

let processText = function (textString, font) {
    var needed = [];
    var ss = textString.toUpperCase();
    for (var i = 0; i < ss.length; i++) {
        var letter = font[ss.charAt(i)];
        if (letter) { // because there's letters I didn't do
            needed.push(letter);
        }
    }

    return _generateBitmapMatrix(needed);
}

module.exports = {
    processPixelText: textString => { return processText(textString, pixel_font_letters) },
    processScoreText: textString => { return processText(textString, score_letters) }
};
